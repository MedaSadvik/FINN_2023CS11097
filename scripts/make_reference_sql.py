"""Generate db/seed_reference.sql: the shared lookup rows the database needs before anyone signs up.

    python scripts/make_reference_sql.py

companies (the 17-stock universe), employers and employer_relations. Public reference data, no personal data.
Run the output once in the Supabase SQL editor, after db/schema.sql.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from pipeline.config import PORTFOLIO

SECTOR_LABEL = {"semis_electronics": "semis_electronics", "ai_cloud": "ai_cloud"}


def q(v):
    return "null" if v is None else "'" + str(v).replace("'", "''") + "'"


def main():
    net = json.loads((ROOT / "data" / "network" / "synthetic_network.json").read_text())
    out = ["-- Generated by scripts/make_reference_sql.py. Do not edit by hand.", ""]
    out.append("insert into companies (ticker, name, sector, in_portfolio) values")
    out.append(",\n".join(f"  ({q(t)}, {q(n)}, {q(s)}, true)" for t, n, s in PORTFOLIO))
    out.append("on conflict (ticker) do nothing;\n")
    out.append("insert into employers (key, name, sector, ticker) values")
    out.append(",\n".join(f"  ({q(e['key'])}, {q(e['name'])}, {q(e['sector'])}, {q(e['ticker'])})" for e in net["employers"]))
    out.append("on conflict (key) do nothing;\n")
    out.append("insert into employer_relations (employer_key, ticker, relation) values")
    out.append(",\n".join(f"  ({q(r['employer_key'])}, {q(r['ticker'])}, {q(r['relation'])})" for r in net["employer_relations"]))
    out.append("on conflict do nothing;")
    (ROOT / "db" / "seed_reference.sql").write_text("\n".join(out) + "\n")
    print(f"wrote db/seed_reference.sql: {len(PORTFOLIO)} companies, {len(net['employers'])} employers, {len(net['employer_relations'])} relations")


if __name__ == "__main__":
    main()
